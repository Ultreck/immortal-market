const COLORS = ['#0088FE', '#00C49F', '#FFBB28', '#FF8042'];

const TemplatePieChart = ({ element }) => {
  const firstObject = data[0];
  const keys = Object.keys(firstObject);
  const firstKey = keys[0];
  const secondKey = keys[1];

  return (
    <ResponsiveContainer width="100%" height="100%">
      <PieChart
        width={500}
        height={300}
        margin={{
          top: 5,
          right: 30,
          left: 20,
          bottom: 5,
        }}
      >
        <Pie
          data={element.chartSettings.data || data}
          nameKey={element.chartSettings.nameKey || firstKey}
          dataKey={element.chartSettings.dataKey || secondKey}
          cx="50%"
          cy="50%"
          innerRadius={0}
          outerRadius={80}
          fill="#8884d8"
          label
        >
          {data.map((entry, index) => (
            <Cell key={`cell-${index}`} fill={COLORS[index % COLORS.length]} />
          ))}
        </Pie>
        <Tooltip />
        <Legend />
      </PieChart>
    </ResponsiveContainer>
  );
};

TemplatePieChart.propTypes = {
  element: PropTypes.shape({
    id: PropTypes.number.isRequired,
    type: PropTypes.string.isRequired,
    x: PropTypes.number.isRequired,
    y: PropTypes.number.isRequired,
    text: PropTypes.string.isRequired,
    width: PropTypes.number.isRequired,
    height: PropTypes.number.isRequired,
    style: PropTypes.object,
    chartSettings: PropTypes.object.isRequired,
  }),
  active: PropTypes.bool.isRequired,
  onClick: PropTypes.func.isRequired,
  onChange: PropTypes.func.isRequired,
  width: PropTypes.number,
  root: PropTypes.any.isRequired,
};

export default TemplatePieChart;

